#!/usr/bin/env node
// Generates the error catalogue artefacts from docs/error-codes.json.
//
// docs/error-codes.json is the single source of truth. This script emits:
//   - docs/error-codes.md   (human-readable catalogue)
//   - src/api/error_codes.rs (typed Rust enum, one variant per code)
//
// Run with: node scripts/generate-error-catalogue.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const jsonPath = resolve(root, "docs/error-codes.json");
const mdPath = resolve(root, "docs/error-codes.md");
const rustPath = resolve(root, "src/api/error_codes.rs");

const codes = JSON.parse(readFileSync(jsonPath, "utf8"));

function statusOf(entry) {
  return Array.isArray(entry.http_status)
    ? entry.http_status.join(", ")
    : String(entry.http_status);
}

// --- Markdown catalogue ---------------------------------------------------

const mdLines = [
  "<!-- Generated by scripts/generate-error-catalogue.mjs from docs/error-codes.json. Do not edit by hand. -->",
  "",
  "# Error codes",
  "",
  "| Code | HTTP status | Description |",
  "| --- | --- | --- |",
];
for (const entry of codes) {
  mdLines.push(`| \`${entry.code}\` | ${statusOf(entry)} | ${entry.description} |`);
}
mdLines.push("");
writeFileSync(mdPath, mdLines.join("\n"));

// --- Rust enum ------------------------------------------------------------

function variantName(code) {
  return code
    .toLowerCase()
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const rustLines = [
  "// @generated by scripts/generate-error-catalogue.mjs from docs/error-codes.json.",
  "// Do not edit by hand; regenerate instead.",
  "",
  "/// Typed error codes derived from `docs/error-codes.json`.",
  "///",
  "/// Using these variants instead of string literals makes typos compile errors",
  "/// and keeps the API catalogue and the code in sync.",
  "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
  "pub enum ErrorCode {",
];
for (const entry of codes) {
  rustLines.push(`    /// ${entry.description}`);
  rustLines.push(`    ${variantName(entry.code)},`);
}
rustLines.push("}", "");
rustLines.push("impl ErrorCode {");
rustLines.push("    /// The canonical wire representation of this code.");
rustLines.push("    pub const fn as_str(self) -> &'static str {");
rustLines.push("        match self {");
for (const entry of codes) {
  rustLines.push(`            ErrorCode::${variantName(entry.code)} => "${entry.code}",`);
}
rustLines.push("        }");
rustLines.push("    }");
rustLines.push("}", "");
rustLines.push("impl std::fmt::Display for ErrorCode {");
rustLines.push("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
rustLines.push("        f.write_str(self.as_str())");
rustLines.push("    }");
rustLines.push("}", "");
rustLines.push("impl From<ErrorCode> for String {");
rustLines.push("    fn from(code: ErrorCode) -> Self {");
rustLines.push("        code.as_str().to_string()");
rustLines.push("    }");
rustLines.push("}", "");
rustLines.push("/// Every code in the catalogue, in catalogue order.");
rustLines.push("pub const ALL: &[ErrorCode] = &[");
for (const entry of codes) {
  rustLines.push(`    ErrorCode::${variantName(entry.code)},`);
}
rustLines.push("];", "");
writeFileSync(rustPath, rustLines.join("\n"));

console.log(`Wrote ${mdPath}`);
console.log(`Wrote ${rustPath}`);
